import re

def clean_text(text: str) -> str:
    # 1. Normalize excessive character repetitions (e.g., 'looooove' -> 'loove')
    text = re.sub(r'(.)\1{2,}', r'\1\1', text)
    # 2. Standardize whitespace
    text = re.sub(r'\s+', ' ', text).strip()
    return text

