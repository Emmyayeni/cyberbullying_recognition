# Tune threshold tau:
# 0.0 is the default decision boundary.
# Increasing (e.g., 0.1 to 0.3) makes the model more conservative before blocking.
# Decreasing (e.g., -0.2 to -0.1) makes it flag aggressively.
DECISION_THRESHOLD = 0.0


def test_text(message: str, threshold: float = DECISION_THRESHOLD):
  score = float(pipeline.decision_function([message])[0])
  is_cyberbullying = score > threshold
  status = "BLOCKED" if is_cyberbullying else "ALLOWED"  #[cite: 1]
  label = "Cyberbullying" if is_cyberbullying else "Safe"  #[cite: 1]

  print(f"Message   : \"{message}\"")
  print(f"Status    : [{status}] -> Classified as {label}")  #[cite: 1]
  print(
      f"Score     : {score:+.4f} (Threshold: {threshold:+.2f})"
  )  #[cite: 1]
  print("-" * 60)


