from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.svm import LinearSVC

# 80/20 train/test split
X_train, X_test, y_train, y_test = train_test_split(
    df["text"], df["label"], test_size=0.20, random_state=42, stratify=df["label"]
)

# Unified Pipeline: TF-IDF vectorizer + Linear Support Vector Machine
pipeline = Pipeline([
    (
        "tfidf",
        TfidfVectorizer(
            lowercase=True,  # Conservative normalization
            ngram_range=(1, 2),  # Captures individual words and two-word phrases
            max_features=15000,  # Caps vocabulary size
            strip_accents="unicode",
        ),
    ),
    ("classifier", LinearSVC(C=1.0, random_state=42, max_iter=2500)),
])

# Train the entire pipeline
pipeline.fit(X_train, y_train)
print("Pipeline training completed.")

from sklearn.metrics import classification_report, confusion_matrix

y_pred = pipeline.predict(X_test)

# Display tabular performance metrics[cite: 1]
print("Classification Report:")
print(
    classification_report(
        y_test, y_pred, target_names=["Safe (0)", "Cyberbullying (1)"]
    )
)

